#!/usr/bin/env python3
"""Split core's and alloc's test suites into parts small enough to run.

Without an MMU every segment of a program is one physically contiguous
block, and the kernel's page allocator gives at most 4 MB; the whole of
coretests or alloctests is more code than that.  Each part is the suite's
own tests/lib.rs -- its crate attributes, macros and helpers -- with only
some of its top-level `mod` lines, written beside it (so the modules'
paths resolve) as c33_partN.rs.  Modules are balanced by source size.

    split.py            writes the parts; core-N/ and alloc-N/ build them
"""

from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
LIBRARY = HERE.parent / "work/rust/library"
PARTS = {"coretests": 3, "alloctests": 3}


def sources(tests, name):
    file = tests / f"{name}.rs"
    folder = tests / name
    return ([file] if file.exists() else []) + (sorted(folder.rglob("*.rs")) if folder.is_dir() else [])


def weight(tests, name):
    file = tests / f"{name}.rs"
    folder = tests / name
    size = file.stat().st_size if file.exists() else 0
    if folder.is_dir():
        size += sum(p.stat().st_size for p in folder.rglob("*.rs"))
    return size


def split(suite, parts):
    tests = LIBRARY / suite / "tests"
    lines = (tests / "lib.rs").read_text().splitlines(keepends=True)
    mod_line = re.compile(r"^(pub )?mod (\w+);")
    mods = [(i, mod_line.match(l).group(2)) for i, l in enumerate(lines) if mod_line.match(l)]
    # A module the others use (crate::NAME: alloctests' testing, with its
    # macros) goes in every part.
    source = {name: "".join(p.read_text() for p in sources(tests, name)) for _, name in mods}
    shared = {name for _, name in mods
              if any(re.search(rf"crate::{name}\b", text)
                     for other, text in source.items() if other != name)}
    bins = [[i for i, name in mods if name in shared] for _ in range(parts)]
    sizes = [0] * parts
    for i, name in sorted(mods, key=lambda m: -weight(tests, m[1])):
        if name in shared:
            continue
        k = sizes.index(min(sizes))
        bins[k].append(i)
        sizes[k] += weight(tests, name)
    entries = []
    for k, keep in enumerate(bins, 1):
        drop = {i for i, _ in mods} - set(keep)
        text = "".join(l for i, l in enumerate(lines) if i not in drop)
        header = (f"// Generated by rust/libtests/split.py: {suite}'s tests/lib.rs with\n"
                  f"// {len(keep)} of its {len(mods)} modules (shared: {', '.join(sorted(shared)) or 'none'}).\n")
        path = tests / f"c33_part{k}.rs"
        if not path.exists() or path.read_text() != header + text:
            path.write_text(header + text)
        entries.append((f"{suite}-{k}", path))
    return entries


def main():
    for suite, parts in PARTS.items():
        split(suite, parts)


if __name__ == "__main__":
    main()
