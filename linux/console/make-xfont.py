#!/usr/bin/env python3
"""Regenerate the built-in X 5x8 font patch from the pinned Unicode BDF.

  make-xfont.py font-misc-misc-1.1.3.tar.xz /path/to/bdftopcf [--check]

The patch stays self-contained; normal system builds need no font generator.
"""
import gzip
import hashlib
from pathlib import Path
import re
import subprocess
import sys
import tarfile

ARCHIVE_SHA256 = "79abe361f58bb21ade9f565898e486300ce1cc621d5285bec26e14b6a8618fed"
PATCH = Path(__file__).resolve().parents[1] / "buildroot/external/patches/xlib_libXfont2/0001-add-the-5x8-built-in-font.patch"


def main():
    if len(sys.argv) not in (3, 4) or (len(sys.argv) == 4 and sys.argv[3] != "--check"):
        sys.exit(__doc__)
    archive = Path(sys.argv[1])
    if hashlib.sha256(archive.read_bytes()).hexdigest() != ARCHIVE_SHA256:
        sys.exit("unexpected font-misc-misc archive SHA-256")
    with tarfile.open(archive) as tar:
        member = next(m for m in tar.getmembers() if m.name.endswith("/5x8.bdf"))
        source = tar.extractfile(member).read()
    # X's core font protocol expands a two-byte font's entire encoding range
    # into a dense metrics reply. Three ligatures at FB00..FB02 and U+FFFD
    # turn this font into 65536 entries (about 790 KiB), requiring a 1 MiB
    # contiguous allocation on NOMMU even though only 1426 glyphs exist.
    # Keep the common range through U+28FF; make the replacement bitmap the
    # default glyph at encoding 0. No glyphs are remapped to other text.
    bdf = source.decode("ascii")
    blocks = re.findall(r"STARTCHAR .*?ENDCHAR\n", bdf, re.S)
    kept = []
    for block in blocks:
        code = int(re.search(r"^ENCODING (\d+)$", block, re.M).group(1))
        if 0 < code < 0x3000:
            kept.append(block)
        elif code == 0xfffd:
            kept.append(re.sub(r"^ENCODING 65533$", "ENCODING 0", block, flags=re.M))
    prefix = bdf.split("STARTCHAR", 1)[0]
    prefix = re.sub(r"^CHARS \d+$", f"CHARS {len(kept)}", prefix, flags=re.M)
    subset = (prefix + "".join(kept) + "ENDFONT\n").encode("ascii")
    pcf = subprocess.run([sys.argv[2]], input=subset, capture_output=True, check=True).stdout
    compressed = bytearray(gzip.compress(pcf, mtime=0))
    compressed[9] = 255  # Stable gzip OS field across Python versions/platforms.
    header = [
        "/* Generated by linux/console/make-xfont.py; do not edit.",
        f" * Public domain X.Org misc-fixed 5x8 ISO10646-1, {len(kept)} glyphs.",
        " * Encodings through U+28FF; U+FFFD's bitmap is the default glyph at 0.",
        " * Source: font-misc-misc-1.1.3.tar.xz, SHA-256 " + ARCHIVE_SHA256 + ".",
        " * Uncompressed PCF SHA-256: " + hashlib.sha256(pcf).hexdigest() + ".",
        " */",
        "static const char file_5x8[] = {",
    ]
    for i in range(0, len(compressed), 12):
        header.append("    " + ", ".join("'\\%03o'" % b for b in compressed[i:i + 12]) + ",")
    header += ["};"]
    old = PATCH.read_text()
    prefix = old.split("diff --git a/src/builtins/font-5x8.h", 1)[0]
    prefix = ("From: Tim Douglas <me@timdoug.com>\n"
              "Subject: [PATCH] Add the 5x8 built-in Unicode font\n\n"
              "Add the public-domain X.Org 5x8 ISO10646-1 font alongside fixed\n"
              "and cursor. The tiny font covers Latin, Greek, Cyrillic and symbols\n"
              "through U+28FF, with a replacement bitmap as its default glyph.\n"
              "This bounds the dense core-font metrics reply on a NOMMU system.\n"
              "without font-file readers or FreeType. Regenerate its PCF with\n"
              "linux/console/make-xfont.py and the pinned font-misc-misc archive.\n\n"
              "Signed-off-by:" + prefix.split("Signed-off-by:", 1)[1])
    prefix = prefix.replace("-misc-fixed-medium-r-normal--8-80-75-75-c-50-iso8859-1",
                            "-misc-fixed-medium-r-normal--8-80-75-75-c-50-iso10646-1")
    patch = (prefix + "diff --git a/src/builtins/font-5x8.h b/src/builtins/font-5x8.h\n"
             "new file mode 100644\n--- /dev/null\n+++ b/src/builtins/font-5x8.h\n"
             f"@@ -0,0 +1,{len(header)} @@\n" +
             "".join("+" + line + "\n" for line in header))
    if len(sys.argv) == 4:
        if patch != old:
            sys.exit("built-in X font patch differs from regeneration")
        print("Built-in X Unicode font matches regeneration")
    else:
        PATCH.write_text(patch)
        print(f"Wrote {PATCH}: {len(pcf)} PCF bytes, {len(compressed)} compressed")


if __name__ == "__main__":
    main()
