#!/usr/bin/env python3
"""Write wr-fonts.h, the panel's bitmap fonts, from their upstream sources.

  make-fonts.py LINUX/lib/fonts/font_6x8.c font-misc-misc-1.1.3.tar.xz > wr-fonts.h

The console keeps the kernel's 6x8 ASCII and CP437-mapped Unicode glyphs,
supplemented by X's public domain ISO10646 5x8 font in six-pixel cells.
The keyboard's labels are X's misc-fixed 6x13. Rows are a byte each, the
leftmost pixel in the high bit. font-misc-misc comes from
https://xorg.freedesktop.org/archive/individual/font/ (SHA-256 79abe361...,
as Buildroot pins it).
"""
import hashlib
import re
import sys
import tarfile
import unicodedata

MISC_SHA256 = "79abe361f58bb21ade9f565898e486300ce1cc621d5285bec26e14b6a8618fed"
UCD = unicodedata.ucd_3_2_0  # Stable database supplied by every supported Python.


def kernel_6x8(path):
    source = open(path).read()
    data = [int(h, 16) for h in
            re.findall(r"0x([0-9A-Fa-f]{2}),", source.split("fontdata_6x8", 1)[1])]
    if len(data) != 256 * 8:
        sys.exit(f"{path}: {len(data)} bytes, expected 2048")
    return [data[c * 8:c * 8 + 8] for c in range(256)], hashlib.sha256(source.encode()).hexdigest()


def misc_fixed(path, name, width, height):
    with tarfile.open(path) as tar:
        member = next(m for m in tar.getmembers() if m.name.endswith("/" + name + ".bdf"))
        bdf = tar.extractfile(member).read().decode("latin-1")
    ascent = int(re.search(r"^FONT_ASCENT (\d+)", bdf, re.M).group(1))
    glyphs = {}
    for block in bdf.split("STARTCHAR")[1:]:
        code = int(re.search(r"^ENCODING (-?\d+)", block, re.M).group(1))
        if not 32 <= code <= 0xffff:
            continue
        w, h, xoff, yoff = map(int, re.search(r"^BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)",
                                               block, re.M).groups())
        bits = block.split("BITMAP", 1)[1].split()[:h]
        rows = [0] * height
        top = ascent - (yoff + h)
        for i, word in enumerate(bits):
            value = int(word, 16)
            bits_per_row = 4 * len(word)
            for x in range(w):
                if value >> (bits_per_row - 1 - x) & 1 and 0 <= top + i < height and 0 <= xoff + x < width:
                    rows[top + i] |= 0x80 >> (xoff + x)
        glyphs[code] = rows
    return glyphs


def table(rows):
    return ",\n".join("\t{ " + ", ".join(f"0x{b:02x}" for b in glyph) + " }"
                      for glyph in rows)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    console, console_sum = kernel_6x8(sys.argv[1])
    keys_sum = hashlib.sha256(open(sys.argv[2], "rb").read()).hexdigest()
    if keys_sum != MISC_SHA256:
        sys.exit("unexpected font-misc-misc archive SHA-256")
    keys = misc_fixed(sys.argv[2], "6x13", 6, 13)
    glyphs = misc_fixed(sys.argv[2], "5x8", 6, 8)
    # Keep the existing ASCII and joined box drawing exactly as before.
    cp437 = [ord(bytes([c]).decode("cp437")) for c in range(256)]
    for c in range(32, 256):
        glyphs[cp437[c]] = console[c]
    # Canonical two-character compositions supported by this font. This is
    # rendering only: the terminal retains the original code points.
    compositions = []
    for c in sorted(glyphs):
        decomp = UCD.decomposition(chr(c)).split()
        if len(decomp) == 2 and not decomp[0].startswith("<"):
            a, b = map(lambda x: int(x, 16), decomp)
            if UCD.normalize("NFC", chr(a) + chr(b)) == chr(c):
                compositions.append((a, b, c))
    compositions.sort()
    unicode_rows = ",\n".join(
        "\t{ 0x%04x, { %s } }" % (c, ", ".join(f"0x{b:02x}" for b in glyphs[c]))
        for c in sorted(glyphs) if c >= 128)
    compose_rows = ",\n".join("\t{ 0x%04x, 0x%04x, 0x%04x }" % row
                                for row in compositions)
    print(f"""// SPDX-License-Identifier: GPL-2.0-only
/*
 * Generated by make-fonts.py; do not edit.
 *
 * console_font: Linux lib/fonts/font_6x8.c (GPL-2.0), SHA-256 {console_sum}.
 * key_font: misc-fixed 6x13.bdf (public domain) from font-misc-misc-1.1.3.tar.xz,
 * SHA-256 {keys_sum}.
 * Unicode supplement: public domain misc-fixed 5x8.bdf from the same archive.
 * Canonical compositions restricted to glyphs above; generated with Python's
 * Unicode {UCD.unidata_version} database.
 */
#ifndef WR_FONTS_H
#define WR_FONTS_H

#include <stdint.h>

#define CONSOLE_FONT_WIDTH	6
#define CONSOLE_FONT_HEIGHT	8
#define KEY_FONT_WIDTH		6
#define KEY_FONT_HEIGHT		13
#define KEY_FONT_FIRST		32
#define KEY_FONT_LAST		126

static const uint8_t console_font[256][CONSOLE_FONT_HEIGHT] = {{
{table(console)}
}};

static const uint8_t key_font[KEY_FONT_LAST - KEY_FONT_FIRST + 1][KEY_FONT_HEIGHT] = {{
{table([keys[c] for c in range(32, 127)])}
}};

static const uint16_t console_cp437[256] = {{
{table([cp437[i:i + 8] for i in range(0, 256, 8)]).replace('{ ', '').replace(' }', '')}
}};

static const struct {{
    uint16_t codepoint;
    uint8_t rows[CONSOLE_FONT_HEIGHT];
}} console_unicode_font[] = {{
{unicode_rows}
}};

static const struct {{
    uint16_t base, mark, composed;
}} console_compositions[] = {{
{compose_rows}
}};

#endif""")


if __name__ == "__main__":
    main()
